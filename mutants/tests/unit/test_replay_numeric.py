"""Numeric replay-agreement regressions (manager-owned; directive Sec 2).

The CEO probe showed set-based comparison passed with a mutated close.
Agreement is now per-symbol ordered full-record: any value mutation,
duplicate, removal, reorder, or symbol-set change must fail the gate.
Expected bars below are hand-computed from the aggregator's documented
causal rules, not generated by the comparison code under test.
"""
import contextlib
import importlib.util
import io
import json
import sys
from argparse import Namespace
from pathlib import Path

TOOLS = Path(__file__).resolve().parents[2] / "tools"
CLASS = "synthetic-test"
T0 = 1_700_000_000_000


def _load():
    spec = importlib.util.spec_from_file_location(
        "replay_stream_numeric", TOOLS / "replay_stream.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _trade(seq, ts, agg_id, price, qty, buyer_is_maker):
    return {"v": 1, "format": "cryptobot-events/1", "input_class": CLASS,
            "source": "synthetic", "route": "test", "run_id": "num",
            "seq": seq, "channel": "aggTrade", "symbol": "TSTUSDT",
            "exchange_ts_ms": ts, "local_recv_ms": ts + 5,
            "local_mono_ns": seq, "gap_kind": None, "venue_seq": agg_id,
            "payload": {"agg_id": agg_id, "price": price, "qty": qty,
                        "first_id": agg_id, "last_id": agg_id,
                        "trade_ts_ms": ts, "buyer_is_maker": buyer_is_maker}}


def _bbo(seq, ts, bid, ask):
    return {"v": 1, "format": "cryptobot-events/1", "input_class": CLASS,
            "source": "synthetic", "route": "test", "run_id": "num",
            "seq": seq, "channel": "bookTicker", "symbol": "TSTUSDT",
            "exchange_ts_ms": ts, "local_recv_ms": ts + 5,
            "local_mono_ns": seq, "gap_kind": None, "venue_seq": 0,
            "payload": {"bid": bid, "ask": ask}}


def _spread(bid, ask):
    return (ask - bid) / ((ask + bid) / 2) * 10_000


def _events():
    return [
        _bbo(1, T0 + 100, 100.0, 100.1),
        _trade(2, T0 + 200, 1, 100.05, 2.0, False),
        _trade(3, T0 + 300, 2, 100.08, 1.0, True),
        _trade(4, T0 + 1600, 3, 100.10, 0.5, False),
        _bbo(5, T0 + 1700, 100.05, 100.15),
        _trade(6, T0 + 3600, 4, 101.0, 1.0, True),
    ]


def _hand_bars():
    # Window T0 closes when trade@T0+1600 advances the watermark past T0+1000.
    # Window T0+1000 closes when trade@T0+3600 advances it; T0+2000 is empty.
    # Window T0+3000 stays open (incomplete at flush) — absent by design.
    return [
        {"type": "bar", "input_class": CLASS, "symbol": "TSTUSDT",
         "window_start_ms": T0, "o": 100.05, "h": 100.08, "l": 100.05,
         "c": 100.08, "volume": 3.0, "trades": 2, "buy_volume": 2.0,
         "first_id": 1, "last_id": 2,
         "spread_bps": _spread(100.0, 100.1), "gap_before": False},
        {"type": "bar", "input_class": CLASS, "symbol": "TSTUSDT",
         "window_start_ms": T0 + 1000, "o": 100.10, "h": 100.10,
         "l": 100.10, "c": 100.10, "volume": 0.5, "trades": 1,
         "buy_volume": 0.5, "first_id": 3, "last_id": 3,
         "spread_bps": _spread(100.05, 100.15), "gap_before": False},
        {"type": "missing", "input_class": CLASS, "symbol": "TSTUSDT",
         "window_start_ms": T0 + 2000, "gap_before": False},
    ]


def _write_run(tmp_path, bars):
    run_dir = tmp_path / "run"
    run_dir.mkdir()
    (run_dir / "events.jsonl").write_text(
        "\n".join(json.dumps(e) for e in _events()) + "\n")
    (run_dir / "bars.jsonl").write_text(
        "\n".join(json.dumps(b) for b in bars) + "\n")
    return run_dir


def _run_replay(module, run_dir):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        code = module.cmd_replay(Namespace(run_dir=str(run_dir), expect_class=CLASS))
    return code, json.loads(buf.getvalue())


def test_hand_computed_bars_agree(tmp_path):
    module = _load()
    code, out = _run_replay(module, _write_run(tmp_path, _hand_bars()))
    assert code == 0
    assert out["bar_rebuild_agrees"] is True
    assert out["first_mismatch"] is None
    assert out["replayed_records"] == 3


def test_mutated_close_fails_like_ceo_probe(tmp_path):
    module = _load()
    bars = _hand_bars()
    bars[0] = dict(bars[0], c=123456789.0)
    code, out = _run_replay(module, _write_run(tmp_path, bars))
    assert code == 1
    assert out["bar_rebuild_agrees"] is False
    assert out["first_mismatch"]["kind"] == "record"
    assert out["first_mismatch"]["differing_fields"]["c"]["captured"] == 123456789.0


def test_duplicate_record_fails(tmp_path):
    module = _load()
    bars = _hand_bars() + [_hand_bars()[0]]
    code, out = _run_replay(module, _write_run(tmp_path, bars))
    assert code == 1 and out["first_mismatch"]["kind"] == "count"


def test_removed_record_fails(tmp_path):
    module = _load()
    code, out = _run_replay(module, _write_run(tmp_path, _hand_bars()[:2]))
    assert code == 1 and out["first_mismatch"]["kind"] == "count"


def test_reordered_series_fails(tmp_path):
    module = _load()
    bars = _hand_bars()
    bars = [bars[1], bars[0], bars[2]]
    code, out = _run_replay(module, _write_run(tmp_path, bars))
    assert code == 1 and out["first_mismatch"]["kind"] == "record"


def test_spread_mutation_fails(tmp_path):
    module = _load()
