#!/usr/bin/env python3
"""Inventory retained capture run-dirs into captured.toml (W2, E-008; B5).

Streams each run's events.jsonl (never loads it whole): per-file sha256,
channels, symbols, row counts, ts ranges, and receipt-idle gaps over 60 s.
run_stats/heartbeat/manifest sidecars are hashed, not parsed.

Usage:
    python build_captured.py --runs /path/to/data/captures --out captured.toml
"""
from __future__ import annotations

import argparse
import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path

FILES = ("events.jsonl", "manifest.json", "heartbeat.json", "run_stats.json")
GAP_MS = 60_000


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _inventory_events(path: Path) -> dict:
    channels: set[str] = set()
    symbols: set[str] = set()
    rows = 0
    ts_min: int | None = None
    ts_max = 0
    gaps: list[tuple[int, int]] = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            if not line.strip():
                continue
            record = json.loads(line)
            rows += 1
            channels.add(str(record.get("channel")))
            symbols.add(str(record.get("symbol")))
            ts = int(record.get("local_recv_ms") or 0)
            if ts_min is None:
                ts_min = ts
            if ts > ts_max + GAP_MS and ts_max:
                gaps.append((ts_max, ts))
            ts_max = max(ts_max, ts)
    return {"rows": rows, "channels": sorted(channels), "symbols": sorted(symbols),
            "ts_min_ms": ts_min or 0, "ts_max_ms": ts_max, "gaps": gaps}


def _toml_str(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--runs", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()
    runs_dir = Path(args.runs)
    run_dirs = sorted(p for p in runs_dir.iterdir() if p.is_dir())
    if not run_dirs:
        print(f"no run dirs in {runs_dir}", flush=True)
        return 2

    lines = [
        "# Retained capture run-dirs, immediate benchmark (W2, E-008; B5).",
        "# Generated by build_captured.py; `local` paths are absolute (durable",
        "# machine-local bulk; raw.jsonl excluded by design, events.jsonl canonical).",
        "",
        "[dataset]",
        f"name = {_toml_str('captured')}",
        f"kind = {_toml_str('captured-runs')}",
        "manifest_version = 1",
        f"created_utc = {_toml_str(datetime.now(timezone.utc).isoformat())}",
        f"runs_dir = {_toml_str(str(runs_dir))}",
        ("notes = " + _toml_str(
            "Live observed-public captures (top-2 USDT perps). raw.jsonl bulk "
            "excluded; bars.jsonl derivable from events.")),
        "",
    ]
    for run_dir in run_dirs:
        for name in FILES:
            path = run_dir / name
            if not path.exists():
                print(f"  skip missing {run_dir.name}/{name}", flush=True)
                continue
            print(f"  hash {run_dir.name}/{name} ...", flush=True)
            lines.append("[[source]]")
            lines.append(f"run_id = {_toml_str(run_dir.name)}")
            lines.append(f"file = {_toml_str(name)}")
            lines.append(f"local = {_toml_str(str(path))}")
            lines.append(f"sha256 = {_toml_str(_sha256(path))}")
            lines.append(f"bytes = {path.stat().st_size}")
            if name == "events.jsonl":
                inv = _inventory_events(path)
                lines.append(f"rows = {inv['rows']}")
                lines.append("channels = [{}]".format(
                    ", ".join(_toml_str(c) for c in inv["channels"])))
                lines.append("symbols = [{}]".format(
                    ", ".join(_toml_str(s) for s in inv["symbols"])))
                lines.append(f"ts_min_ms = {inv['ts_min_ms']}")
                lines.append(f"ts_max_ms = {inv['ts_max_ms']}")
                for start, end in inv["gaps"]:
                    lines.append("")
                    lines.append("[[gap]]")
                    lines.append(f"run_id = {_toml_str(run_dir.name)}")
                    lines.append(f"start_ms = {start}")
                    lines.append(f"end_ms = {end}")
                    lines.append(f"reason = {_toml_str('receipt-idle-60s+')}")
            lines.append("")
    Path(args.out).write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {args.out}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
